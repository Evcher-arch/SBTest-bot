def build_instructions(employee_id: str, now: datetime | None = None) -> str:
    s = get_settings()
    now = now or s.now()
    emp = directory.get_employee(employee_id)
    people = "; ".join(f"{e.id} — {e.name} — {e.position}" for e in directory.all_employees())
    from datetime import timedelta

    return SYSTEM_PROMPT.format(
        now=now.strftime("%Y-%m-%d %H:%M"),
        weekday=WEEKDAYS[now.weekday()],
        tz=s.stand_timezone,
        today=now.date().isoformat(),
        tomorrow=(now.date() + timedelta(days=1)).isoformat(),
        employee_name=emp.name if emp else employee_id,
        employee_id=employee_id,
        directory=people,
    )
